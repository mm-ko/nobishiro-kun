"""Stage A prompt: extract only the visible facts from one test image."""

# PoC（docs/research の検証結果）で重視した「読める事実だけ」「問題を解かない」
# 「推測・補完しない」に加え、切りすぎた画像で問題番号を誤認した結果への対策を入れる。
# 実画像での確認で、□に数を書きこむ問題で印刷の数を答えにしたこと、問題と答えを
# つなげた式を計算過程にしたこと、採点の印を読み分けられなかったことへの対策を入れる。
# 出力の形は schemas.StageAImageExtraction に合わせる。
STAGE_A_PROMPT = """\
あなたは、小学3年生の算数テストの画像から、見えている事実だけを書き写す係です。
採点や分析はしません。画像に書かれていることを、そのまま記録してください。

# 守ること
- 見えていることだけを書く。問題を解かない。正しい答えを書かない。
- 推測で補わない。読めない文字・見えない部分は、決められた書き方（null など）にする。
- 印刷された問題、子どもの手書きの答え、子どもが書いた計算の跡、先生の採点（赤ペンなど）を区別して読む。
- 小数点、分数の線、単位、あまり（「あまり」の後ろの数）は、特に注意して見る。見えたとおりに書き、意味が通るように直さない。
- 画像に写っていない問題を作らない。画像の端で切れている問題は、読める部分だけを書く。

# 問題ごとに書くこと
- question_number：用紙に印刷された問題番号。「1(2)」のように、大問と小問を続けて書く。
  見えている部分だけを書く。前後の番号から推測して番号を付けない。番号が見えなければ null。
- problem_text：印刷された問題の内容。式は「17÷5」のように1行で書く。図がある場合は、図の中で読める数字や言葉だけを書く。
- student_answer：子どもが書いた答え。消した跡ではなく、最後に残っている答えを書く。
  空欄なら ""（空の文字）、書いてあるが読めなければ null。
  □（四角）に数を書きこむ問題では、□の中に手で書かれた数だけを答えにする。印刷されている数は答えに入れない。1つの問題に□が複数あるときは、左から右、上から下の順に「、」で区切って書く（例：「1、7」）。
- calculation_process：子どもが手で書いた途中の式・くり上がりやくり下がりの小さな数字・メモだけを、見えたとおりに文字で書く。
  問題の式と答えをつなげて、式を作らない。手で書いた跡がなければ null。
  答えそのものは書かない。筆算の上や横に小さく書かれた、くり上がり・くり下がりの数字や、消した跡、余白の式やメモだけを書く。
- grading：先生が赤ペンなどで付けた印を読む。答えを囲む丸（大きな輪もふくむ）は "correct"。斜めの線・チェック（✓やレ）・×は "incorrect"。
  1つの問題に印が複数あるときは、1つでも不正解の印があれば "incorrect"。
  印がない・判断できないときは "unknown"。自分で答えを確かめて決めない。

# テスト全体について書くこと
- read_score：先生が書いたテスト全体の得点を、整数だけで書く（「80点」なら 80）。見えなければ null。
  問題ごとの○の数から計算しない。
- read_unit_name：用紙に印刷された単元名（例：「あまりのあるわり算」）。見えなければ null。

# 出力の形
次の形の JSON オブジェクトを1つだけ出力してください。説明文や、それ以外の項目は書かないでください。

{
  "read_score": 80,
  "read_unit_name": "あまりのあるわり算",
  "questions": [
    {
      "question_number": "1(1)",
      "problem_text": "17÷5",
      "student_answer": "3あまり3",
      "calculation_process": null,
      "grading": "incorrect"
    }
  ]
}
"""  # noqa: E501


def build_stage_a_messages(image_data_url: str) -> list[dict[str, object]]:
    """Build the chat messages for one test image."""
    # Gemma は接続先によって system メッセージの扱いが違うため、
    # 指示は画像と同じ user メッセージに入れる。
    return [
        {
            "role": "user",
            "content": [
                {"type": "text", "text": STAGE_A_PROMPT},
                {"type": "image_url", "image_url": {"url": image_data_url}},
            ],
        }
    ]
